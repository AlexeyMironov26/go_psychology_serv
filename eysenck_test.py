# ─────────────────────────────────────────────
# Ключ подсчёта
# ─────────────────────────────────────────────
# Экстраверсия: «да» на вопросы 1,3,8,10,13,17,22,25,27,39,44,46,49,53,56
#               «нет» на вопросы 5,15,20,29,32,37,41,51
EXTRAVERSION_YES = {1, 3, 8, 10, 13, 17, 22, 25, 27, 39, 44, 46, 49, 53, 56}
EXTRAVERSION_NO  = {5, 15, 20, 29, 32, 37, 41, 51}

# Невротизм: «да» на вопросы 2,4,7,9,11,14,16,19,21,23,26,28,31,33,35,38,40,43,45, 47, 50,52,55,57
NEUROTICISM_YES  = {2, 4, 7, 9, 11, 14, 16, 19, 21, 23, 26, 28, 31, 33, 35, 38, 40, 43, 45, 47, 50, 52, 55, 57}

# Ложь: «да» на вопросы 6,24,36; «нет» на вопросы 12,18,30,42,48,54
LIE_YES = {6, 24, 36}
LIE_NO  = {12, 18, 30, 42, 48, 54}


def calculate_eysenck_scores(answers: list) -> dict:
    """
    answers — список словарей {'question_number': int, 'answer': int}
    answer: 1 = «да», 0 = «нет»
    Возвращает dict с ключами extraversion, neuroticism, lie.
    """
    extraversion = 0
    neuroticism = 0
    lie = 0

    for item in answers:
        q = item['question_number']
        a = item['answer']

        if q in EXTRAVERSION_YES and a == 1:
            extraversion += 1
        if q in EXTRAVERSION_NO and a == 0:
            extraversion += 1

        if q in NEUROTICISM_YES and a == 1:
            neuroticism += 1

        if q in LIE_YES and a == 1:
            lie += 1
        if q in LIE_NO and a == 0:
            lie += 1

    return {
        'extraversion': extraversion,
        'neuroticism': neuroticism,
        'lie': lie,
    }


def interpret_eysenck(scores: dict) -> str:
    """Возвращает текстовую интерпретацию результатов для пользователя."""
    e = scores['extraversion']
    n = scores['neuroticism']

    # Экстраверсия / интроверсия
    if e >= 15:
        e_label = "экстраверт"
    elif e >= 9:
        e_label = "амбиверт"
    else:
        e_label = "интроверт"

    # Нейротизм
    if n >= 17:
        n_label = "с эмоциональной нестабильностью"
    elif n >= 13:
        n_label = "с высоким уровнем эмоциональности"
    elif n >= 9:
        n_label = "со средним уровнем эмоциональности"
    else:
        n_label = "с эмоциональной устойчивостью"
    
    lie = scores['lie']

    result = f"По результатам прохождения теста вы {e_label} {n_label}."

    if lie >= 6:
        result += "\n\n⚠️ Возможно, вы были не до конца искренны в своих ответах."

    return result


def save_eysenck_result(db_path: str, telegram_id: int, scores: dict,
                        snapshot_name: str, snapshot_group: str, snapshot_faculty: str) -> bool:
    """Сохраняет результат теста Айзенка в БД."""
    try:
        conn = sqlite3.connect(db_path, timeout=5)
        cursor = conn.cursor()

        cursor.execute('SELECT id FROM users WHERE telegram_id = ?', (telegram_id,))
        user = cursor.fetchone()
        if not user:
            cursor.execute('SELECT id FROM users ORDER BY id DESC LIMIT 1')
            user = cursor.fetchone()
        if not user:
            logger.error("No users found in database")
            return False

        user_id = user[0]

        moscow_tz = timezone(timedelta(hours=3))
        now_moscow = datetime.now(moscow_tz).strftime('%Y-%m-%d %H:%M:%S')

        cursor.execute('''
            INSERT INTO eysenck_test_results
            (user_id, snapshot_full_name, snapshot_user_group, snapshot_faculty,
             extraversion, neuroticism, lie, completed_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        ''', (
            user_id,
            snapshot_name,
            snapshot_group,
            snapshot_faculty,
            scores['extraversion'],
            scores['neuroticism'],
            scores['lie'],
            now_moscow
        ))

        conn.commit()
        conn.close()
        logger.info(f"Eysenck result saved for user_id: {user_id}")
        return True

    except Exception as e:
        logger.error(f"Error saving eysenck result: {e}")
        return False
